-- =============================================================================
--  GESTIÓN DE ÓRDENES OPERATIVAS - MODELO FÍSICO (ORACLE 19c+ / 23ai)
--  Tablas: TIPO_ORDEN, CLIENTE, ORDEN, ORDEN_HISTORICO, TRANSICION_ESTADO,
--          ORDEN_ERROR_LOG
--
--  Estrategia de alto volumen (~1M órdenes/mes, ~5M cambios de estado/mes):
--   * ORDEN y ORDEN_HISTORICO particionadas por RANGO + INTERVALO mensual.
--     Oracle crea automáticamente la partición del mes al primer INSERT.
--     -> partition pruning en consultas por rango de fechas
--     -> archivado / compresión / purga por partición (DDL, sin DELETE masivo)
--   * Índices LOCALES alineados con la partición para los filtros del API.
--   * PK de ORDEN con índice GLOBAL particionado por HASH para evitar la
--     contención "right-hand index block" con IDs secuenciales crecientes.
--   * Secuencias con CACHE alto (INCREMENT BY 50 = allocationSize de JPA).
--   * Catálogos pequeños (TRANSICION_ESTADO) como IOT.
--   * Todas las FK tienen índice (evita bloqueos TM sobre la tabla hija).
--
--  Convención de fechas: todas las columnas TIMESTAMP se almacenan en UTC.
-- =============================================================================
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK
SET ECHO ON
SET DEFINE OFF

-- -----------------------------------------------------------------------------
-- TIPO_ORDEN (catálogo)
-- -----------------------------------------------------------------------------
CREATE TABLE TIPO_ORDEN (
    CODIGO              VARCHAR2(30)    NOT NULL,
    DESCRIPCION         VARCHAR2(200)   NOT NULL,
    SLA_HORAS           NUMBER(5)       DEFAULT 72  NOT NULL,
    ACTIVO              CHAR(1)         DEFAULT 'S' NOT NULL,
    -- auditoría
    CREADO_POR          VARCHAR2(100)   DEFAULT ON NULL USER NOT NULL,
    FECHA_CREACION      TIMESTAMP(6)    DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
    MODIFICADO_POR      VARCHAR2(100),
    FECHA_MODIFICACION  TIMESTAMP(6),
    CONSTRAINT PK_TIPO_ORDEN        PRIMARY KEY (CODIGO),
    CONSTRAINT CK_TIPO_ORDEN_ACTIVO CHECK (ACTIVO IN ('S', 'N')),
    CONSTRAINT CK_TIPO_ORDEN_SLA    CHECK (SLA_HORAS > 0)
);

COMMENT ON TABLE  TIPO_ORDEN        IS 'Catálogo de tipos de orden operativa';
COMMENT ON COLUMN TIPO_ORDEN.SLA_HORAS IS 'Acuerdo de nivel de servicio en horas';

-- -----------------------------------------------------------------------------
-- CLIENTE
-- -----------------------------------------------------------------------------
CREATE TABLE CLIENTE (
    ID_CLIENTE          NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 CACHE 100) NOT NULL,
    TIPO_DOCUMENTO      VARCHAR2(5)     NOT NULL,
    NUMERO_DOCUMENTO    VARCHAR2(20)    NOT NULL,
    NOMBRE              VARCHAR2(200)   NOT NULL,
    EMAIL               VARCHAR2(150),
    TELEFONO            VARCHAR2(30),
    DIRECCION           VARCHAR2(250),
    ESTADO              VARCHAR2(10)    DEFAULT 'ACTIVO' NOT NULL,
    VERSION             NUMBER(10)      DEFAULT 0 NOT NULL,
    -- auditoría
    CREADO_POR          VARCHAR2(100)   DEFAULT ON NULL USER NOT NULL,
    FECHA_CREACION      TIMESTAMP(6)    DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
    MODIFICADO_POR      VARCHAR2(100),
    FECHA_MODIFICACION  TIMESTAMP(6),
    CONSTRAINT PK_CLIENTE           PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UK_CLIENTE_DOCUMENTO UNIQUE (TIPO_DOCUMENTO, NUMERO_DOCUMENTO),
    CONSTRAINT CK_CLIENTE_ESTADO    CHECK (ESTADO IN ('ACTIVO', 'INACTIVO')),
    CONSTRAINT CK_CLIENTE_TIPO_DOC  CHECK (TIPO_DOCUMENTO IN ('CC', 'CE', 'NIT', 'PAS', 'TI'))
);

COMMENT ON TABLE CLIENTE IS 'Clientes (suscriptores) de la empresa de servicios públicos';

-- -----------------------------------------------------------------------------
-- TRANSICION_ESTADO (máquina de estados parametrizable, IOT)
-- -----------------------------------------------------------------------------
CREATE TABLE TRANSICION_ESTADO (
    ESTADO_ORIGEN          VARCHAR2(20)  NOT NULL,
    ESTADO_DESTINO         VARCHAR2(20)  NOT NULL,
    REQUIERE_OBSERVACION   CHAR(1)       DEFAULT 'N' NOT NULL,
    ACTIVO                 CHAR(1)       DEFAULT 'S' NOT NULL,
    -- auditoría
    CREADO_POR             VARCHAR2(100) DEFAULT ON NULL USER NOT NULL,
    FECHA_CREACION         TIMESTAMP(6)  DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
    MODIFICADO_POR         VARCHAR2(100),
    FECHA_MODIFICACION     TIMESTAMP(6),
    CONSTRAINT PK_TRANSICION_ESTADO PRIMARY KEY (ESTADO_ORIGEN, ESTADO_DESTINO),
    CONSTRAINT CK_TRANS_ORIGEN  CHECK (ESTADO_ORIGEN  IN ('REGISTRADA','ASIGNADA','EN_EJECUCION','SUSPENDIDA','EJECUTADA','CERRADA','CANCELADA')),
    CONSTRAINT CK_TRANS_DESTINO CHECK (ESTADO_DESTINO IN ('REGISTRADA','ASIGNADA','EN_EJECUCION','SUSPENDIDA','EJECUTADA','CERRADA','CANCELADA')),
    CONSTRAINT CK_TRANS_DISTINTO CHECK (ESTADO_ORIGEN <> ESTADO_DESTINO),
    CONSTRAINT CK_TRANS_REQ_OBS CHECK (REQUIERE_OBSERVACION IN ('S', 'N')),
    CONSTRAINT CK_TRANS_ACTIVO  CHECK (ACTIVO IN ('S', 'N'))
) ORGANIZATION INDEX;

COMMENT ON TABLE TRANSICION_ESTADO IS 'Transiciones de estado permitidas para una orden';

-- -----------------------------------------------------------------------------
-- ORDEN (particionada por mes de creación)
-- -----------------------------------------------------------------------------
-- INCREMENT BY 50 = allocationSize de Hibernate (optimizador pooled): la app
-- reserva bloques de 50 IDs por cada viaje a la BD.
CREATE SEQUENCE SEQ_ORDEN START WITH 1 INCREMENT BY 50 CACHE 1000 NOCYCLE;

CREATE TABLE ORDEN (
    ID_ORDEN            NUMBER(19)      NOT NULL,
    ID_CLIENTE          NUMBER(19)      NOT NULL,
    CODIGO_TIPO_ORDEN   VARCHAR2(30)    NOT NULL,
    ESTADO              VARCHAR2(20)    DEFAULT 'REGISTRADA' NOT NULL,
    PRIORIDAD           VARCHAR2(10)    DEFAULT 'MEDIA' NOT NULL,
    DESCRIPCION         VARCHAR2(1000)  NOT NULL,
    DIRECCION_SERVICIO  VARCHAR2(250),
    FECHA_ESTADO        TIMESTAMP(6)    DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
    VERSION             NUMBER(10)      DEFAULT 0 NOT NULL,      -- bloqueo optimista
    -- auditoría
    CREADO_POR          VARCHAR2(100)   NOT NULL,
    FECHA_CREACION      TIMESTAMP(6)    DEFAULT ON NULL SYSTIMESTAMP NOT NULL,  -- clave de partición
    MODIFICADO_POR      VARCHAR2(100),
    FECHA_MODIFICACION  TIMESTAMP(6),
    CONSTRAINT FK_ORDEN_CLIENTE   FOREIGN KEY (ID_CLIENTE)        REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_ORDEN_TIPO      FOREIGN KEY (CODIGO_TIPO_ORDEN) REFERENCES TIPO_ORDEN (CODIGO),
    CONSTRAINT CK_ORDEN_ESTADO    CHECK (ESTADO IN ('REGISTRADA','ASIGNADA','EN_EJECUCION','SUSPENDIDA','EJECUTADA','CERRADA','CANCELADA')),
    CONSTRAINT CK_ORDEN_PRIORIDAD CHECK (PRIORIDAD IN ('BAJA','MEDIA','ALTA','CRITICA')),
    CONSTRAINT CK_ORDEN_VERSION   CHECK (VERSION >= 0)
)
PARTITION BY RANGE (FECHA_CREACION) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION P_ORDEN_HISTORICA VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00')
);

-- PK con índice GLOBAL particionado por HASH: reparte las inserciones de IDs
-- consecutivos en 16 segmentos y evita el "hot block" del índice.
CREATE UNIQUE INDEX PK_ORDEN ON ORDEN (ID_ORDEN)
    GLOBAL PARTITION BY HASH (ID_ORDEN) PARTITIONS 16;
ALTER TABLE ORDEN ADD CONSTRAINT PK_ORDEN PRIMARY KEY (ID_ORDEN) USING INDEX PK_ORDEN;

-- Índices LOCALES (uno por partición) para los filtros del endpoint de listado
--  GET /orden?estado=&fechaInicio=&fechaFin=
CREATE INDEX IX_ORDEN_ESTADO_FECHA ON ORDEN (ESTADO, FECHA_CREACION) LOCAL;
CREATE INDEX IX_ORDEN_FECHA        ON ORDEN (FECHA_CREACION, ID_ORDEN) LOCAL;
-- Índices de FK (consultas por cliente y prevención de bloqueos TM)
CREATE INDEX IX_ORDEN_CLIENTE      ON ORDEN (ID_CLIENTE, FECHA_CREACION) LOCAL;
CREATE INDEX IX_ORDEN_TIPO         ON ORDEN (CODIGO_TIPO_ORDEN) LOCAL;

COMMENT ON TABLE  ORDEN              IS 'Órdenes operativas. Particionada mensualmente por FECHA_CREACION';
COMMENT ON COLUMN ORDEN.VERSION      IS 'Versión para control de concurrencia optimista';
COMMENT ON COLUMN ORDEN.FECHA_ESTADO IS 'Fecha (UTC) del último cambio de estado';

-- -----------------------------------------------------------------------------
-- ORDEN_HISTORICO (trazabilidad / auditoría, solo inserción)
-- -----------------------------------------------------------------------------
CREATE TABLE ORDEN_HISTORICO (
    ID_HISTORICO        NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 1 CACHE 1000) NOT NULL,
    ID_ORDEN            NUMBER(19)      NOT NULL,
    ESTADO_ANTERIOR     VARCHAR2(20),                     -- NULL en la creación
    ESTADO_NUEVO        VARCHAR2(20)    NOT NULL,
    OBSERVACION         VARCHAR2(1000),
    VERSION_ORDEN       NUMBER(10)      NOT NULL,         -- versión resultante de la orden
    ORIGEN              VARCHAR2(30)    DEFAULT 'API' NOT NULL,
    CORRELATION_ID      VARCHAR2(64),                     -- traza extremo a extremo (logs <-> BD)
    ID_TRANSACCION      VARCHAR2(64),                     -- id de transacción Oracle
    USUARIO             VARCHAR2(100)   NOT NULL,         -- usuario de negocio
    USUARIO_BD          VARCHAR2(128),                    -- usuario de sesión Oracle
    FECHA_CAMBIO        TIMESTAMP(6)    DEFAULT ON NULL SYSTIMESTAMP NOT NULL,  -- clave de partición
    CONSTRAINT PK_ORDEN_HISTORICO PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_HIST_ORDEN      FOREIGN KEY (ID_ORDEN) REFERENCES ORDEN (ID_ORDEN),
    CONSTRAINT CK_HIST_ESTADO_NUEVO CHECK (ESTADO_NUEVO IN ('REGISTRADA','ASIGNADA','EN_EJECUCION','SUSPENDIDA','EJECUTADA','CERRADA','CANCELADA')),
    CONSTRAINT CK_HIST_ORIGEN       CHECK (ORIGEN IN ('API', 'BATCH', 'PLSQL', 'INTEGRACION'))
)
PARTITION BY RANGE (FECHA_CAMBIO) INTERVAL (NUMTOYMINTERVAL(1, 'MONTH'))
(
    PARTITION P_HIST_HISTORICA VALUES LESS THAN (TIMESTAMP '2026-01-01 00:00:00')
);

-- Índice GLOBAL: la consulta del historial de una orden (por ID_ORDEN) no
-- conoce la fecha; un índice global evita sondear todas las particiones.
-- También cubre la FK. Mantenimiento de particiones con UPDATE GLOBAL INDEXES.
CREATE INDEX IX_HIST_ORDEN ON ORDEN_HISTORICO (ID_ORDEN, FECHA_CAMBIO);
-- Consultas de auditoría por rango de fechas / usuario
CREATE INDEX IX_HIST_FECHA_USUARIO ON ORDEN_HISTORICO (FECHA_CAMBIO, USUARIO) LOCAL;
CREATE INDEX IX_HIST_CORRELATION   ON ORDEN_HISTORICO (CORRELATION_ID) LOCAL;

COMMENT ON TABLE ORDEN_HISTORICO IS 'Historial inmutable de cambios de estado de las órdenes (auditoría)';

-- -----------------------------------------------------------------------------
-- ORDEN_ERROR_LOG (intentos fallidos, registrados con transacción autónoma)
-- -----------------------------------------------------------------------------
CREATE TABLE ORDEN_ERROR_LOG (
    ID_ERROR            NUMBER(19)      GENERATED BY DEFAULT ON NULL AS IDENTITY (CACHE 100) NOT NULL,
    ID_ORDEN            NUMBER(19),
    ESTADO_SOLICITADO   VARCHAR2(30),
    CODIGO_ERROR        NUMBER(10)      NOT NULL,
    MENSAJE             VARCHAR2(4000)  NOT NULL,
    BACKTRACE           VARCHAR2(4000),
    USUARIO             VARCHAR2(100),
    CORRELATION_ID      VARCHAR2(64),
    FECHA_ERROR         TIMESTAMP(6)    DEFAULT ON NULL SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ORDEN_ERROR_LOG PRIMARY KEY (ID_ERROR)
);
CREATE INDEX IX_ERROR_LOG_FECHA ON ORDEN_ERROR_LOG (FECHA_ERROR);
CREATE INDEX IX_ERROR_LOG_ORDEN ON ORDEN_ERROR_LOG (ID_ORDEN);

COMMENT ON TABLE ORDEN_ERROR_LOG IS 'Intentos rechazados de cambio de estado (auditoría de errores)';

-- -----------------------------------------------------------------------------
-- TRIGGERS DE AUDITORÍA
-- -----------------------------------------------------------------------------
-- Completa los datos técnicos de trazabilidad en cada inserción del histórico.
CREATE OR REPLACE TRIGGER TRG_ORDEN_HIST_BI
BEFORE INSERT ON ORDEN_HISTORICO
FOR EACH ROW
BEGIN
    :NEW.ID_TRANSACCION := NVL(:NEW.ID_TRANSACCION, DBMS_TRANSACTION.LOCAL_TRANSACTION_ID);
    :NEW.USUARIO_BD     := SYS_CONTEXT('USERENV', 'SESSION_USER');
    :NEW.FECHA_CAMBIO   := NVL(:NEW.FECHA_CAMBIO, SYSTIMESTAMP);
END;
/

-- El histórico es de SOLO INSERCIÓN: cualquier UPDATE/DELETE es rechazado.
-- (La purga por retención se hace con DROP/EXCHANGE PARTITION, que es DDL.)
CREATE OR REPLACE TRIGGER TRG_ORDEN_HIST_INMUTABLE
BEFORE UPDATE OR DELETE ON ORDEN_HISTORICO
BEGIN
    RAISE_APPLICATION_ERROR(-20010, 'ORDEN_HISTORICO es inmutable: solo se permiten inserciones (auditoría)');
END;
/

EXIT
